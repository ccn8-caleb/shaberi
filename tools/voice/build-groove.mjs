// Generate the voices for 相づちグルーヴ: the friend's lines (春日部つむぎ) and the model
// answers (剣崎雌雄), from site/js/game/groove.js.
//
//   docker run -d --rm --name voicevox -p 127.0.0.1:50021:50021 voicevox/voicevox_engine:cpu-latest
//   node tools/voice/build-groove.mjs
//
// Writes site/audio/groove/*.mp3 and site/js/data/groove-audio.js. Each clip records
// its onset (when the voice becomes audible) so the game can place it on the beat,
// and its length. Lines are sped up if needed to fit LINE_MAX.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { SAMPLE_RATE, speak, encodeWav, onsetOf, engineVersion } from './voicevox.mjs';
import { SONG, LINE_MAX } from '../../site/js/game/groove.js';
import { analyze } from '../../site/js/engine/pitch.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const DIR = path.join(ROOT, 'site/audio/groove');
const MANIFEST = path.join(ROOT, 'site/js/data/groove-audio.js');
const FRIEND = 'tsumugi';
const MODEL = 'kenzaki';
const engine = await engineVersion();
fs.mkdirSync(DIR, { recursive: true });

async function make(voice, text, { maxLength = Infinity } = {}) {
  let speed = 1;
  let pcm;
  let length;
  for (let tries = 0; tries < 4; tries++) {
    pcm = await speak(voice, text, { speed, pre: 0.02, post: 0.12 });
    const { span } = analyze(pcm, SAMPLE_RATE);
    length = span.end - span.start;
    if (length <= maxLength) break;
    speed *= (length / maxLength) * 1.03;
  }
  if (length > maxLength) console.warn(`"${text}" is ${length.toFixed(2)} s, over ${maxLength.toFixed(2)} s`);
  const id = crypto.createHash('sha1').update(JSON.stringify([engine, voice, text, speed])).digest('hex').slice(0, 10);
  const rel = `audio/groove/${voice}-${id}.mp3`;
  const tmp = path.join(DIR, `.${id}.wav`);
  fs.writeFileSync(tmp, encodeWav(pcm));
  execFileSync('ffmpeg', ['-loglevel', 'error', '-y', '-i', tmp, '-af', 'loudnorm=I=-18:TP=-1.5:LRA=11', '-ar', String(SAMPLE_RATE), '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '48k', path.join(ROOT, 'site', rel)]);
  fs.unlinkSync(tmp);
  // Measure the final file, as the game will play it.
  const raw = execFileSync('ffmpeg', ['-loglevel', 'error', '-i', path.join(ROOT, 'site', rel), '-f', 's16le', '-ac', '1', '-ar', String(SAMPLE_RATE), '-']);
  const played = new Float32Array(raw.length / 2);
  for (let i = 0; i < played.length; i++) played[i] = raw.readInt16LE(i * 2) / 32768;
  const { span } = analyze(played, SAMPLE_RATE);
  process.stdout.write(`${voice}:${text} `);
  return { src: rel, onset: +onsetOf(played).toFixed(3), end: +span.end.toFixed(3), speed: +speed.toFixed(3) };
}

// Start fresh: clip names include a hash, so old ones would linger.
for (const f of fs.readdirSync(DIR)) if (f.endsWith('.mp3')) fs.unlinkSync(path.join(DIR, f));
const lines = {};
const answers = {};
for (const s of SONG) {
  lines[s.line] ||= await make(FRIEND, s.line, { maxLength: LINE_MAX });
  answers[s.you] ||= await make(MODEL, s.you);
}

fs.writeFileSync(
  MANIFEST,
  `// Generated by tools/voice/build-groove.mjs: do not edit by hand.
// Voices for 相づちグルーヴ. onset = seconds before the voice is audible (place the clip
// that much early to land on the beat); end = seconds until the voice has finished.
// Made with VOICEVOX (VOICEVOX:春日部つむぎ, VOICEVOX:剣崎雌雄); not MIT-licensed.

export const GROOVE_AUDIO = ${JSON.stringify({ engine, lines, answers }, null, 2)};
`
);
console.log(`\n${Object.keys(lines).length} lines, ${Object.keys(answers).length} answers`);
